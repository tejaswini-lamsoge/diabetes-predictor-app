import { useLocation, useNavigate, useParams } from "react-router-dom";

function Result() {
  const { assessmentId } = useParams();
  const location = useLocation();
  const navigate = useNavigate();

  const result = location.state?.result;
  const patient = location.state?.patient;

  // If someone opens /result directly without an assessment
  if (!result) {
    return (
      <div className="result-empty">

        <h1>
          No Assessment Found
        </h1>

        <p>
          Please complete an assessment before viewing results.
        </p>

        <button
          className="primary-button"
          onClick={() => navigate("/assessment")}
        >
          Start Assessment
        </button>

      </div>
    );
  }

  const isPositive = result.prediction === 1;

  const assessmentDate = result.created_at
  ? new Date(result.created_at).toLocaleString(
      "en-GB",
      {
        dateStyle: "medium",
        timeStyle: "short",
      }
    )
  : "Not available";

  return (
    <div className="result-page">

      {/* PAGE HEADER */}

      <div className="page-header">

        <div>

          <p className="page-eyebrow">
            ASSESSMENT COMPLETED
          </p>

          <h1>
            AI Assessment Result
          </h1>

          <p className="page-description">
            Review the result generated from the submitted
            patient information and symptoms.
          </p>

        </div>

      </div>


      {/* RESULT HERO */}

      <section
        className={`result-hero ${
          isPositive
            ? "result-hero-positive"
            : "result-hero-negative"
        }`}
      >

        <div className="result-status">

          <span className="result-status-label">
            MODEL RESULT
          </span>

          <h2>
            {result.result}
          </h2>

          <p>
            AI-based diabetes prediction
          </p>

        </div>


        <div className="result-score">

          <span>
            Model-estimated probability
          </span>

          <strong>
            {result.probability}%
          </strong>

        </div>

      </section>


      {/* ASSESSMENT INFORMATION */}

      <div className="result-grid">

        {/* PATIENT INFORMATION */}

        <section className="result-card">

          <div className="result-card-header">

            <h2>
              Patient Information
            </h2>

          </div>

          <div className="result-details">

            <div className="detail-item">

              <span>
                Age
              </span>

              <strong>
                {patient?.Age}
              </strong>

            </div>


            <div className="detail-item">

              <span>
                Gender
              </span>

              <strong>
                {patient?.Gender}
              </strong>

            </div>


            <div className="detail-item">

              <span>
                Assessment Date
              </span>

              <strong>
                {assessmentDate}
              </strong>

            </div>

          </div>

        </section>


        {/* ASSESSMENT SUMMARY */}

        <section className="result-card">

          <div className="result-card-header">

            <h2>
              Assessment Summary
            </h2>

          </div>

<div className="result-details">

  <div className="detail-item">

    <span>
      Assessment ID
    </span>

    <strong>
      {result.assessment_id}
    </strong>

  </div>


  <div className="detail-item">

    <span>
      Result
    </span>

    <strong>
      {result.result}
    </strong>

  </div>


  <div className="detail-item">

    <span>
      Model probability
    </span>

    <strong>
      {result.probability}%
    </strong>

  </div>


  <div className="detail-item">

    <span>
      Model
    </span>

    <strong>
      {result.model}
    </strong>

  </div>


  <div className="detail-item">

    <span>
      Model version
    </span>

    <strong>
      {result.model_version}
    </strong>

  </div>

</div>

        </section>

      </div>


      {/* CLINICAL NOTICE */}

      <section className="clinical-notice">

        <div className="notice-icon">
          i
        </div>

        <div>

          <h3>
            Important information
          </h3>

          <p>
            This result is generated by an artificial
            intelligence model based on the information
            provided during the assessment.
          </p>

          <p>
            It is intended as decision-support information
            and should not be considered a medical diagnosis.
            A qualified healthcare professional should review
            symptoms and relevant clinical information before
            making healthcare decisions.
          </p>

        </div>

      </section>


      {/* ACTIONS */}

      <div className="result-actions">

        <button
          className="secondary-button"
          onClick={() => navigate("/")}
        >
          ← Back to Dashboard
        </button>


        <button
          className="primary-button"
          onClick={() => navigate("/assessment")}
        >
          New Assessment →
        </button>

      </div>

    </div>
  );
}

export default Result;